/* 
- Objetos funcionam como array associativo de outras linguagens
- Podemos criar propriedades com chave e objeto
- A ideia é guardar um conjunto de valores para aplicar posteriormente
*/

var objeto = {
    nome: "Matheus",
    idade: 18,
    profissão: "Inutíl",
};

console.log(objeto);

console.log(objeto.nome);
console.log(objeto.idade);
console.log(objeto.profissão);

console.log("Minha idade é" + objeto.idade);
